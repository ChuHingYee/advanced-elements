import type { ShallowRef } from 'vue'
import type { TableRendererExpose } from '../../utils/table-drag'
import { inject, shallowRef } from 'vue'
import { advTableCurrentRowKey } from '../../types/injection-keys'
import { ADV_TABLE_COLUMN_KEY_ATTR, ADV_TABLE_ROW_KEY_ATTR, getMarkedChildKeys } from '../../utils/table-drag'

/**
 * <zh/> 获取共享的 currentRow 引用——三源合一（架构收敛）。
 *
 * <zh/> default/virtual 渲染器禁止各持一个本地 currentRow shallowRef，选择编排器禁止再持一个
 * <zh/> 后备 ref 并靠 watch 手工和解（渲染器挂载恢复/读时回写），杜绝三份真源。
 * <zh/> 必须由选择域经域键持有唯一 ref；渲染器经注入取同一引用，
 * <zh/> 选择编排器直接读写该 ref——写入路径单一，无需任何和解逻辑。
 * <zh/> 注入缺失时（组合式单测直连、无 provider 的独立使用）回退为本地 ref，保持可独立实例化。
 *
 * <en/> Shared currentRow reference — three-sources-unified (architecture convergence).
 *
 * <en/> The default/virtual renderers must not each hold a local currentRow shallowRef plus a
 * <en/> fallback ref in the selection orchestrator reconciled by a hand-written watch — no three
 * <en/> sources of truth. The selection domain owns THE single ref; renderers obtain it
 * <en/> via injection and the selection orchestrator reads/writes it directly — one write path,
 * <en/> zero reconciliation. When injection is absent (standalone composable tests / provider-less
 * <en/> usage) it falls back to a local ref so the composables stay independently instantiable.
 */
export function useSharedCurrentRow<T>(): ShallowRef<T | null> {
  const rowRef = inject(advTableCurrentRowKey, undefined)
  return (rowRef as ShallowRef<T | null> | undefined) ?? shallowRef<T | null>(null)
}

/**
 * <zh/> 渲染器 expose 配置——两种渲染器通过此配置注入各自的 DOM 查询策略
 * <en/> Renderer expose config — each renderer injects its own DOM query strategy through this config
 */
export interface RendererExposeConfig {
  /** <zh/> 获取表格根 DOM 元素 | <en/> Get table root DOM element */
  getRootEl: () => HTMLElement | null
  /** <zh/> 获取列拖拽容器 | <en/> Get column drag container */
  getColumnDragContainer: () => HTMLElement | null
  /** <zh/> 获取行拖拽容器 | <en/> Get row drag container */
  getRowDragContainer: () => HTMLElement | null
  /** <zh/> 默认列拖拽 handle 选择器 | <en/> Default column drag handle selector */
  defaultColumnDragHandle: string
  /** <zh/> 默认行拖拽 handle 选择器 | <en/> Default row drag handle selector */
  defaultRowDragHandle: string
  /** <zh/> 列可拖拽元素选择器 | <en/> Column draggable element selector */
  columnDraggableSelector: string
}

/**
 * <zh/> 创建渲染器 expose 对象——统一 getRenderedColumnKeys/getRenderedRowKeys 等通用 DOM 查询方法
 *
 * <en/> Create renderer expose object — unifies common DOM query methods like getRenderedColumnKeys/getRenderedRowKeys
 *
 * @remarks
 * <zh/> 两种渲染器（ElTable / ElTableV2）共用此工厂，消除约 100 行结构性重复代码。
 * <zh/> 各渲染器仅需提供自身的 DOM 查询策略（容器选择器、handle 选择器），通用方法由工厂统一生成。
 * <zh/> setCurrentRow/getCurrentRow 收敛至选择编排器（同一 shared ref 的唯一门面），不再由渲染器 expose 重复暴露。
 * <en/> Both renderers (ElTable / ElTableV2) share this factory, eliminating ~100 lines of structural duplication.
 * <en/> Each renderer only provides its own DOM query strategy (container selectors, handle selectors); common methods are generated by the factory.
 * <en/> setCurrentRow/getCurrentRow have been converged to the selection orchestrator (the single facade for the same shared ref), no longer redundantly exposed by the renderer.
 *
 * @param config - <zh/> 渲染器特定配置 | <en/> renderer-specific config
 * @returns <zh/> 渲染器 expose 对象 | <en/> renderer expose object
 */
export function createRendererExpose(
  config: RendererExposeConfig,
): TableRendererExpose {
  function getRenderedColumnKeys(): string[] {
    return getMarkedChildKeys(config.getColumnDragContainer(), ADV_TABLE_COLUMN_KEY_ATTR)
  }

  function getRenderedRowKeys(): string[] {
    return getMarkedChildKeys(config.getRowDragContainer(), ADV_TABLE_ROW_KEY_ATTR)
  }

  return {
    getColumnDragContainer: config.getColumnDragContainer,
    getRowDragContainer: config.getRowDragContainer,
    getRenderedColumnKeys,
    getRenderedRowKeys,
    getDefaultColumnDragHandle: () => config.defaultColumnDragHandle,
    getDefaultRowDragHandle: () => config.defaultRowDragHandle,
    getColumnDraggableSelector: () => config.columnDraggableSelector,
  }
}
